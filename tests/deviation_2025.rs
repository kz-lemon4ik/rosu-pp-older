#[test]
fn a_play_with_only_oks_on_speed_notes_still_gets_finite_pp() {
    let map = Beatmap::from_bytes(MAP.as_bytes()).unwrap();
    for (n300, n100, n50) in [(0, 80, 0), (2, 75, 3), (0, 70, 10), (10, 70, 0)] {
        let pp = osu_2025::OsuPP::new(&map)
            .mods(0)
            .lazer(false)
            .combo(80)
            .n300(n300)
            .n100(n100)
            .n50(n50)
            .misses(0)
            .calculate()
            .unwrap()
            .pp;
        assert!(pp.is_finite(), "{n300}/{n100}/{n50} gave {pp}");
    }
}
